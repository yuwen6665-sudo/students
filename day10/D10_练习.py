#  判断字符串正读反读是否相同（忽略大小写）
#
#  验收：
#      is_palindrome("abcba")  → True
#      is_palindrome("hello")  → False
#      is_palindrome("Abcba")  → True
#      is_palindrome("")       → True   （空字符串算回文）
#
#  【思路】
#      转小写 → 和它的反转比。反转用 s[::-1]
# ============================================================

# ↓↓↓ 在这里写你的代码 ↓↓↓

def is_palindrome(lest):
    lest=lest.lower().strip()
    if lest == lest[::-1]:
        return True
    return  False


# ============================================================
#  第 5 题 · 最大子序和　【★★★】（做不出来正常）
# ------------------------------------------------------------
#  给定整数列表，找出一段连续子数组，使它的和最大，返回这个最大和
#
#  验收：
#      max_sub([-2,1,-3,4,-1,2,1,-5,4])  → 6   （4 + (-1) + 2 + 1 = 6）
#      max_sub([1])                      → 1
#      max_sub([-5,-2,-9])               → -2  （全是负数，最大就是最大的那个）
#      max_sub([])                       → 0
#
#  【思路（最重要的题，务必先自己想 20 分钟）】
#      维护两个变量：
#        current —— 以当前元素结尾的最大和
#        best    —— 到目前为止见过的最大和
#      遍历每个数：
#        current = max(current + n, n)
#        （意思是：要么接上前面，要么从当前重新开始——如果前面的和是负的，不如不要）
#        best = max(best, current)
#
#  这个思路叫「Kadane 算法」，面试高频。
#  核心一句话：**如果前面的累计和变成负数，就扔掉重新开始。**
# ============================================================

# ↓↓↓ 在这里写你的代码 ↓↓↓

def max_sub(nums):
    if not nums:
        return 0
    best = nums[0]
    start = end = 0
    for i in range(len(nums)):
        cur = 0
        for j in range(i, len(nums)):
            cur += nums[j]
            if cur > best:
                best = cur
                start = i
                end = j
    print(f"最大子数组：第 {start + 1}~{end + 1} 个，和 = {best}")
    return best



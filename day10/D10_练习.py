# ============================================================
#  第 3 题 · 字符频次排序　【★★】
# ------------------------------------------------------------
#  统计字符串里每个字符出现次数（忽略空格），
#  返回按次数降序的列表 [(字符, 次数), ...]
#
#  验收：
#      char_count("aabbbc")  → [('b',3), ('a',2), ('c',1)]
#      char_count("")        → []
#
#  【思路】和词频统计完全同一个套路：
#      ① 字典计数：count[ch] = count.get(ch, 0) + 1
#      ② 转列表：list(count.items())
#      ③ 排序：key=lambda x: (-x[1], x[0])
# ============================================================

# ↓↓↓ 在这里写你的代码 ↓↓↓

# ---- 第 3 题 字符频次 ----
def char_count(s):
    count = {}
    for ch in s:
        if ch == " ":
            continue
        count[ch] = count.get(ch, 0) + 1
    items = list(count.items())
    items.sort(key=lambda x: (-x[1], x[0]))
    return items


